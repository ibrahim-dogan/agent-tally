#!/usr/bin/env python3
"""Rasterize Inter into 4-bit anti-aliased bitmap fonts for the firmware.

    python3 -m pip install pillow
    python3 firmware/tools/mkfont.py      # writes firmware/src/fonts/*.h

Covers ASCII, Latin-1 and Latin Extended-A (Turkish, German, most European
languages) plus a few typographic symbols. Inter is SIL OFL 1.1 (see fonts/).
"""

import os
from PIL import ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "fonts")

FACES = {"R": "Inter-Regular.otf", "B": "Inter-SemiBold.otf"}
# name -> (face, pixel size). The UI picks a set by screen width.
FONTS = {
    "inter_r12": ("R", 12), "inter_r13": ("R", 13), "inter_b14": ("B", 14), "inter_b19": ("B", 19),
    "inter_b28": ("B", 28),
    "inter_r16": ("R", 16), "inter_r17": ("R", 17), "inter_b18": ("B", 18), "inter_b25": ("B", 25),
    "inter_b36": ("B", 36),
}

CODEPOINTS = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) +
              [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2190, 0x2192])


def build(name, face, size):
    font = ImageFont.truetype(os.path.join(HERE, "fonts", FACES[face]), size)
    ascent, descent = font.getmetrics()
    glyphs, bits = [], bytearray()
    for cp in CODEPOINTS:
        ch = chr(cp)
        if cp != 0x20 and font.getmask(ch).getbbox() is None:
            continue  # glyph missing in the face
        adv = int(round(font.getlength(ch)))
        mask, (ox, oy) = font.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        bbox = mask.getbbox() if w and h else None
        if bbox is None:
            glyphs.append((cp, 0, 0, 0, 0, adv, len(bits)))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        off = len(bits)
        nib = []
        for y in range(y0, y1):
            for x in range(x0, x1):
                nib.append((mask.getpixel((x, y)) * 15 + 127) // 255)
        if len(nib) % 2:
            nib.append(0)
        bits.extend((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
        glyphs.append((cp, w, h, ox + x0, ascent + oy + y0, adv, off))

    lines = [f"// Generated by tools/mkfont.py from {FACES[face]} @ {size}px. Inter: SIL OFL 1.1.",
             "#pragma once", '#include "../font.h"', "",
             f"static const uint8_t {name}_bits[] = {{"]
    for i in range(0, len(bits), 24):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const AtGlyph {name}_glyphs[] = {{")
    for cp, w, h, x, y, adv, off in glyphs:
        lines.append(f"  {{0x{cp:04x},{w},{h},{x},{y},{adv},{off}}},")
    lines.append("};")
    lines.append(f"static const AtFont {name} = {{{name}_bits, {name}_glyphs, {len(glyphs)}, "
                 f"{ascent + descent}, {ascent}}};")
    with open(os.path.join(OUT, name + ".h"), "w") as f:
        f.write("\n".join(lines) + "\n")
    return len(bits) + len(glyphs) * 10


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, (face, size) in FONTS.items():
        n = build(name, face, size)
        print(f"{name:12} {n / 1024:6.1f} KB")


if __name__ == "__main__":
    main()
